"""Onboarding: prepares the folder the user drops into the agent.

Scaffold with named subfolders + guided briefing; status says what is missing before
intake runs. Whatever is optional is stated as optional — never blocks on a whim.
"""

import os
import re

IMG_EXT = (".png", ".jpg", ".jpeg", ".webp")
FONT_EXT = (".otf", ".ttf", ".ttc")
VID_EXT = (".mp4", ".mov", ".webm", ".m4v")
DOC_EXT = (".pdf", ".docx", ".md", ".txt", ".rtf")
# Briefing supporting documents: ad copy, layout rules, safe areas, logo safety —
# as text, PDF/Word, image (diagrams) or spreadsheet (copy table).
BRIEF_DOC_EXT = DOC_EXT + IMG_EXT + (".csv", ".xlsx")
BRIEF_DOCS_DIR = "briefing"
# Free technical direction for the whole creation, filled in the wizard next to the briefing.
DIRECTION_FILE = "direction.md"

SLOTS = [
    {"key": "logo", "dir": "logo", "label": "Logo", "ext": IMG_EXT, "multiple": False,
     "required": True,
     "hint": "PNG with transparent background, preferably. The proposed palette comes from it."},
    {"key": "refs", "dir": "refs", "label": "Look references", "ext": IMG_EXT, "multiple": True,
     "required": False,
     "hint": "2 to 6 images of ads/posts with the desired look. The agent views them and cross-references the briefing to write the art direction."},
    {"key": "brandbook", "dir": "brandbook", "label": "Brandbook (brand manual)",
     "ext": DOC_EXT + IMG_EXT, "multiple": True, "required": False,
     "hint": "Optional. PDF, images or docx with the brand rules (colors, typography, logo usage, voice). The agent reads them and follows them alongside the briefing and references."},
    {"key": "fonts", "dir": "fonts", "label": "Brand fonts", "ext": FONT_EXT, "multiple": True,
     "required": False,
     "hint": ".otf / .ttf. Without them I use system substitutes and tell you exactly which."},
    {"key": "photos", "dir": "photos", "label": "Photos for the pieces", "ext": IMG_EXT, "multiple": True,
     "required": False,
     "hint": "Photos that can become a piece. Without them the provider generates — and the cost estimate appears before generating."},
    {"key": "videos", "dir": "videos", "label": "Videos", "ext": VID_EXT, "multiple": True,
     "required": False,
     "hint": "Source clips or motion references. New videos are generated by the provider (e.g. Magnific via MCP), with a cost estimate before generating."},
]

BRIEFING_TEMPLATE = """# Campaign briefing

<!-- Fill in what you know. Anything left blank becomes a single question at the end of onboarding. -->

## 1. Business and product
_fill in: what the company sells, in one sentence._

## 2. Audience
_fill in: who decides the purchase._

## 3. Goal, offer and CTA
_fill in: what the campaign should do and the button text._

## 4. Tone of voice
_fill in: how the brand speaks — and what it can never promise._

## 5. Channels
_fill in: Meta, Google, LinkedIn, print, web…_

## 6. Languages
_fill in: e.g. en, pt-BR._

## 7. Concepts (visual directions)
_fill in: how many different directions you want and the name of each, comma-separated — e.g. clean, editorial, cinema. Each concept becomes a template, a delivery folder and a review filter._

## 8. Visual direction
_fill in: what to copy from the references and what to avoid._

## 9. Compliance
_fill in: mandatory disclaimer, forbidden color, term that must not wrap._

## 10. Existing assets
_fill in: photos and videos you can already use (and whether you hold the rights)._
"""

# Unfilled-section marker — the concept parser and status use it.
_UNFILLED = ("_fill in",)

REQUIRED_SECTIONS = ("1.", "2.", "3.")
CONCEPT_SECTION = "7."


def scaffold(inbox):
    os.makedirs(inbox, exist_ok=True)
    for s in SLOTS:
        os.makedirs(os.path.join(inbox, s["dir"]), exist_ok=True)
    os.makedirs(os.path.join(inbox, BRIEF_DOCS_DIR), exist_ok=True)
    brief = os.path.join(inbox, "briefing.md")
    if not os.path.isfile(brief):
        with open(brief, "w", encoding="utf-8") as f:
            f.write(BRIEFING_TEMPLATE)
    return brief


def _sections(text):
    out = []
    for m in re.finditer(r"^## (.+)$", text, re.M):
        start = m.end()
        nxt = re.search(r"^## ", text[start:], re.M)
        body = text[start:start + nxt.start()] if nxt else text[start:]
        body = re.sub(r"<!--.*?-->", "", body, flags=re.S).strip()
        filled = bool(body) and not any(p in body for p in _UNFILLED)
        out.append({"title": m.group(1).strip(), "filled": filled, "body": body})
    return out


def _concept_slug(raw):
    raw = re.sub(r"^\s*(?:[-*•]|\d+[.)])\s*", "", raw.strip())
    return re.sub(r"[^a-z0-9]+", "-", raw.lower()).strip("-")


def requested_concepts(text):
    """Concept names requested in briefing section 7. Comma, semicolon or newline
    separated list; a 'concepts:' marker takes precedence. It is a hint for the agent
    in plan, not a rigid contract — long prose is discarded."""
    sec = next((s for s in _sections(text) if s["title"].startswith(CONCEPT_SECTION)), None)
    if not sec or not sec["filled"]:
        return []
    body = sec["body"]
    m = re.search(r"concepts\s*:\s*(.+)", body, re.I | re.S)
    if m:
        body = m.group(1)
    out = []
    for raw in re.split(r"[,;\n]+|\s+and\s+", body):
        raw = raw.strip()
        if not raw or any(p in raw for p in _UNFILLED) or len(raw.split()) > 3:
            continue
        slug = _concept_slug(raw)
        if slug and len(slug) <= 24 and slug not in out:
            out.append(slug)
    return out


def read_direction(inbox):
    """The technical direction for the whole creation ('' when the user left it empty)."""
    p = os.path.join(inbox, DIRECTION_FILE)
    if not os.path.isfile(p):
        return ""
    with open(p, encoding="utf-8") as f:
        return f.read()


def save_direction(inbox, text):
    with open(os.path.join(inbox, DIRECTION_FILE), "w", encoding="utf-8") as f:
        f.write(text or "")


def status(inbox):
    slots = {}
    for s in SLOTS:
        d = os.path.join(inbox, s["dir"])
        files = []
        if os.path.isdir(d):
            for f in sorted(os.listdir(d)):
                if f.startswith(".") or not f.lower().endswith(s["ext"]):
                    continue
                p = os.path.join(d, f)
                files.append({"name": f, "size": os.path.getsize(p),
                              "rel": os.path.join(s["dir"], f)})
        slots[s["key"]] = {**{k: s[k] for k in ("label", "hint", "required", "multiple", "dir")},
                           "ext": list(s["ext"]), "files": files, "ok": bool(files)}
    brief = os.path.join(inbox, "briefing.md")
    text = ""
    if os.path.isfile(brief):
        with open(brief, encoding="utf-8") as f:
            text = f.read()
    sections = _sections(text)
    missing = [x["title"] for x in sections
               if not x["filled"] and x["title"].startswith(REQUIRED_SECTIONS)]
    docs_dir = os.path.join(inbox, BRIEF_DOCS_DIR)
    docs = []
    if os.path.isdir(docs_dir):
        for f in sorted(os.listdir(docs_dir)):
            if f.startswith(".") or not f.lower().endswith(BRIEF_DOC_EXT):
                continue
            p = os.path.join(docs_dir, f)
            docs.append({"name": f, "size": os.path.getsize(p),
                         "rel": os.path.join(BRIEF_DOCS_DIR, f)})
    return {"inbox": os.path.abspath(inbox), "slots": slots,
            "briefing": {"text": text, "sections": sections, "missing": missing,
                         "concepts": requested_concepts(text)},
            "direction": read_direction(inbox),
            "briefing_docs": docs,
            "ready": slots["logo"]["ok"] and not missing}